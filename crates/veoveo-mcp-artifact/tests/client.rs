const MIB: u64 = 1024 * 1024;

fn ledger_slug() -> ServerSlug {
    ServerSlug::parse("ledger").unwrap()
}

/// The byte at `offset` of every generated body, so a test can check any range.
fn byte_at(offset: u64) -> u8 {
    (offset.wrapping_mul(0x9E37_79B1) >> 11) as u8
}

fn generated(range: std::ops::Range<u64>) -> Vec<u8> {
    range.map(byte_at).collect()
}

/// A body of `length` generated bytes, streamed in uneven chunks so that chunk and part
/// boundaries differ.
fn streamed(length: u64) -> UploadBody {
    const CHUNK: u64 = MIB + 4099;
    let chunks = (0..length.div_ceil(CHUNK)).map(move |index| {
        let start = index * CHUNK;
        Ok(Bytes::from(generated(start..(start + CHUNK).min(length))))
    });
    UploadBody::stream(stream::iter(chunks))
}

fn sha256_of(length: u64) -> Sha256Digest {
    let mut hasher = Sha256::new();
    let mut offset = 0;
    while offset < length {
        let end = (offset + MIB).min(length);
        hasher.update(generated(offset..end));
        offset = end;
    }
    Sha256Digest::from_bytes(hasher.finalize().into())
}

/// A forwarded token for the test user, as the Hub forwards one to `server` with
/// its signed request context.
fn forwarded(server: ServerSlug, permissions: BTreeSet<PermissionName>) -> IssuedHubInternalToken {
    let principal = testing::principal();
    let authority = testing::authority();
    let now = Utc::now();
    let context = HubRequestContext {
        audit: veoveo_audit_contract::AuditRequest::background(),
        access_token: AccessTokenSubject {
            issuer: principal.issuer.clone(),
            subject: principal.subject.clone(),
            oauth_client_id: OAuthClientId::parse(testing::TEST_CLIENT).unwrap(),
            session_family: None,
            audience: ProtectedResourceId::parse(testing::TEST_RESOURCE).unwrap(),
            work_context: authority.work_context.clone(),
            invocation_mode: InvocationMode::Direct,
            initiator: Some(principal.id.clone()),
            delegation_id: None,
            scopes: principal.scopes.clone(),
            jwt_id: None,
            issued_at: now,
            not_before: None,
            expires_at: now + TimeDelta::minutes(5),
        },
        principal: principal.clone(),
    };
    HubInternalTokenIssuer::new(
        TokenIssuer::parse(testing::TEST_ISSUER).unwrap(),
        testing::signing_key(),
    )
    .unwrap()
    .issue(ForwardedRequest {
        profile: HubProfileId::parse(MESH_PROFILE).unwrap(),
        server,
        audience: ResourceIndicator::parse(testing::TEST_RESOURCE).unwrap(),
        client: OAuthClientId::parse(testing::TEST_CLIENT).unwrap(),
        actor: principal,
        authority,
        permissions,
        request_context: Some(context),
        acting_server: None,
        acting_task: None,
        delegation_context: None,
        expires_at: now + TimeDelta::minutes(5),
    })
    .unwrap()
}

/// Artifact and Ledger on one mesh, with Ledger using Artifact's read and write
/// permissions and the test user holding `granted`.
struct Mesh {
    running: RunningMesh,
    ledger: ServerCalls,
    http: reqwest::Client,
    /// Hands Artifact's changes to its subscription hubs, as the hosted process does.
    watching: tokio::task::JoinHandle<()>,
}

impl Drop for Mesh {
    fn drop(&mut self) {
        self.watching.abort();
    }
}

impl Mesh {
    async fn start(harness: &Harness, granted: &[ArtifactPermission]) -> Self {
        // reqwest is built without a TLS provider; components use rustls with ring.
        let _ = rustls::crypto::ring::default_provider().install_default();
        let mut mesh = TestMesh::bind().await;
        mesh.register((*AUTHORIZATION).clone());
        let hubs = Arc::new(TenantHubs::default());
        let watching = tokio::spawn(watch_changes(harness.platform.clone(), hubs.clone()));
        let app = Arc::new(ArtifactApp {
            service: (*harness.service).clone(),
            hubs,
        });
        mesh.serve(
            testing::for_domain::<ArtifactMcp>()
                .handler(move || {
                    Hosted::new(ArtifactMcp::new(app.clone()))
                        .with_tasks(ListenOnly::new(ArtifactSubscriptions::new(app.clone())))
                })
                .build(),
        );
        let mut declaration = ledger::authorization().unwrap();
        declaration.uses.extend([
            ArtifactPermission::ArtifactsRead.name(),
            ArtifactPermission::ArtifactsWrite.name(),
        ]);
        let ledger = mesh.register(declaration);
        // Ledger's tally Tasks run long enough to upload from.
        let tasks = LedgerTasks::new(Duration::from_secs(90));
        mesh.serve(
            testing::for_domain::<LedgerDomain>()
                .handler(move || ledger::hosted(tasks.clone()))
                .build(),
        );
        let running = mesh
            .granting(
                granted
                    .iter()
                    .map(|permission| permission.name())
                    .chain([PermissionName::parse("ledger.entries.read").unwrap()]),
            )
            .start();
        Self {
            running,
            ledger,
            http: reqwest::Client::new(),
            watching,
        }
    }

    /// Artifact for the caller of a request Ledger serves, as `ctx.client()` binds it.
    fn for_request(&self) -> ArtifactClient {
        let issued = forwarded(
            ledger_slug(),
            [PermissionName::parse("ledger.entries.read").unwrap()].into(),
        );
        let calls: HubClient = self
            .ledger
            .for_request(&issued.identity, &ForwardedBearer::new(issued.bearer_token));
        ArtifactClient::new(calls, self.http.clone())
    }

    /// Artifact for the caller of a Ledger Task that a request started and returned, and
    /// that Task as Ledger identifies it.
    async fn for_task(&self) -> (ArtifactClient, OpaqueTaskId) {
        let started = self
            .running
            .start_task("ledger", "tally", json!({"entries": 1}))
            .await;
        let task = started["result"]["taskId"]
            .as_str()
            .unwrap_or_else(|| panic!("no Task started: {started}"));
        let calls = self.ledger.for_task_id(
            TaskId::parse(task).unwrap(),
            &HubProfileId::parse(MESH_PROFILE).unwrap(),
        );
        (
            ArtifactClient::new(calls, self.http.clone()),
            OpaqueTaskId::parse(task).unwrap(),
        )
    }
}

/// Artifact's store caller for the test user, as Artifact builds it from a direct call.
fn user_caller() -> Caller {
    identity::caller(&forwarded(veoveo_mcp_artifact::server(), BTreeSet::new()).identity).unwrap()
}

/// The artifact once Artifact finished verifying it.
async fn verified(harness: &Harness, artifact: &ArtifactRecord) -> ArtifactRecord {
    let caller = user_caller();
    tokio::time::timeout(Duration::from_secs(60), async {
        loop {
            let current = harness
                .service
                .artifact(&caller, artifact.artifact_id, Utc::now())
                .await
                .unwrap();
            if current.state != ArtifactState::Verifying {
                return current;
            }
            tokio::time::sleep(Duration::from_millis(100)).await;
        }
    })
    .await
    .expect("the artifact verified within a minute")
}

fn name(name: &str) -> ArtifactName {
    ArtifactName::parse(name).unwrap()
}

fn octets() -> MediaType {
    MediaType::parse("application/octet-stream").unwrap()
}

fn full_access() -> [ArtifactPermission; 2] {
    [
        ArtifactPermission::ArtifactsRead,
        ArtifactPermission::ArtifactsWrite,
    ]
}

#[tokio::test]
async fn a_request_binding_uploads_and_downloads_for_its_caller() {
    with_service(|harness| async move {
        let stop = CancellationToken::new();
        let worker = tokio::spawn(run_verifications(harness.service.clone(), stop.clone()));
        let mesh = Mesh::start(&harness, &full_access()).await;
        let artifacts = mesh.for_request();

        // A small body of unknown size takes one PUT that declares its size and SHA-256.
        let small = generated(0..1000);
        let artifact = artifacts
            .upload(
                name("small.bin"),
                octets(),
                UploadBody::bytes(small.clone()),
            )
            .await
            .unwrap();
        assert_eq!(artifact.state, ArtifactState::Available);
        assert_eq!(artifact.size, Some(ObjectSize::new(1000).unwrap()));
        assert_eq!(artifact.sha256, Some(sha256_of(1000)));
        assert_eq!(artifact.provenance.acting_server, Some(ledger_slug()));
        assert_eq!(artifact.provenance.task, None);
        assert_eq!(artifact.provenance.caller, testing::principal().id);
        let whole = artifacts.download(artifact.artifact_id).await.unwrap();
        assert_eq!(whole.length, Some(1000));
        assert_eq!(whole.body.collect().await.unwrap(), small);

        // A larger stream of unknown size goes in parts of 16 MiB, four at a time.
        let length = 40 * MIB + 4321;
        let uploaded = artifacts
            .upload(name("large.bin"), octets(), streamed(length))
            .max_size(ObjectSize::new(64 * MIB).unwrap())
            .await
            .unwrap();
        // Without a wait, the upload resolves while Artifact still verifies the bytes.
        assert_eq!(uploaded.state, ArtifactState::Verifying);
        let large = verified(&harness, &uploaded).await;
        assert_eq!(large.state, ArtifactState::Available);
        assert_eq!(large.size, Some(ObjectSize::new(length).unwrap()));
        assert_eq!(large.sha256, Some(sha256_of(length)));
        assert_eq!(large.provenance.acting_server, Some(ledger_slug()));

        // Ranges across a part boundary and to the end.
        let across = artifacts
            .download(large.artifact_id)
            .range(16 * MIB - 10..=16 * MIB + 9)
            .await
            .unwrap();
        assert_eq!(across.length, Some(20));
        assert_eq!(
            across.body.collect().await.unwrap(),
            generated(16 * MIB - 10..16 * MIB + 10)
        );
        let tail = artifacts
            .download(large.artifact_id)
            .range_from(length - 100)
            .await
            .unwrap();
        assert_eq!(
            tail.body.collect().await.unwrap(),
            generated(length - 100..length)
        );
        stop.cancel();
        worker.await.unwrap().unwrap();
    })
    .await;
}

#[tokio::test]
async fn a_task_binding_uploads_after_its_request_returned() {
    with_service(|harness| async move {
        let stop = CancellationToken::new();
        let worker = tokio::spawn(run_verifications(harness.service.clone(), stop.clone()));
        let mesh = Mesh::start(&harness, &full_access()).await;
        let (artifacts, task) = mesh.for_task().await;

        // A known size beyond one PUT streams in parts, two at a time, each one signed
        // and sent again on its own.
        // The upload waits for Artifact's verification Task through the artifact's
        // resource updates, so it resolves available.
        let length = 20 * MIB + 7;
        let artifact = artifacts
            .upload(name("render.bin"), octets(), streamed(length))
            .size(ObjectSize::new(length).unwrap())
            .parallelism(NonZeroUsize::new(2).unwrap())
            .until_verified(Duration::from_secs(60))
            .await
            .unwrap();
        assert_eq!(artifact.state, ArtifactState::Available);
        assert_eq!(artifact.sha256, Some(sha256_of(length)));
        assert_eq!(artifact.provenance.acting_server, Some(ledger_slug()));
        assert_eq!(artifact.provenance.task, Some(task));
        let head = artifacts
            .download(artifact.artifact_id)
            .range(0..=99)
            .await
            .unwrap();
        assert_eq!(head.body.collect().await.unwrap(), generated(0..100));
        stop.cancel();
        worker.await.unwrap().unwrap();
    })
    .await;
}

#[tokio::test]
async fn a_caller_without_the_write_permission_is_refused() {
    with_service(|harness| async move {
        let mesh = Mesh::start(&harness, &[ArtifactPermission::ArtifactsRead]).await;
        let refused = mesh
            .for_request()
            .upload(name("a.txt"), octets(), UploadBody::bytes("abc"))
            .await;
        match refused {
            Err(ArtifactClientError::Call(CallError::Rejected { message, .. })) => {
                assert!(message.contains("artifact.artifacts.write"), "{message}");
            }
            other => panic!("expected Artifact to refuse the upload, got {other:?}"),
        }
    })
    .await;
}

/// The details of every record of `T`'s class in the test user's tenant, each with the
/// acting server and Task its envelope names.
async fn audit_details<T: AuditDetailType>(harness: &Harness) -> Vec<(T, Option<AuditVia>)> {
    let registry = Arc::new(audit_registry().unwrap());
    let reader = AuditStore::new(harness.db.connect().await, registry.clone());
    let tenant: TenantId = testing::principal().tenant.unwrap();
    let mut query = AuditQuery::new(AuditPartition::Tenant(tenant.clone()));
    query.limit = 100;
    reader
        .page(&AuditReadScope::new(Some(tenant), false), &query)
        .await
        .unwrap()
        .records
        .iter()
        .filter(|record| record.draft.class().to_string() == T::CLASS)
        .map(|record| {
            (
                registry
                    .read(record.draft.class(), record.draft.detail())
                    .unwrap(),
                record.draft.via().cloned(),
            )
        })
        .collect()
}

#[tokio::test]
async fn the_acting_server_and_its_task_are_named_in_the_audit_records() {
    with_service(|harness| async move {
        let mesh = Mesh::start(&harness, &full_access()).await;
        let direct = mesh
            .for_request()
            .upload(name("a.txt"), octets(), UploadBody::bytes("audited"))
            .await
            .unwrap();
        let (from_task, task) = mesh.for_task().await;
        let tasked = from_task
            .upload(name("b.txt"), octets(), UploadBody::bytes("from a Task"))
            .await
            .unwrap();
        assert_eq!(tasked.provenance.task, Some(task.clone()));

        let created: Vec<(UploadCreated, _)> = audit_details(&harness).await;
        let completed: Vec<(UploadCompleted, _)> = audit_details(&harness).await;
        // Ledger's Tasks run in core's Task runtime, so the envelope names the Task by its
        // core identifier.
        let ledger_task = TaskId::parse(task.as_str()).unwrap();
        for (artifact, acting_task) in [(&direct, None), (&tasked, Some(ledger_task))] {
            let via = Some(AuditVia {
                server: ledger_slug(),
                task: acting_task,
            });
            let created: Vec<_> = created
                .iter()
                .filter(|(detail, _)| detail.artifact_id == artifact.artifact_id)
                .collect();
            assert_eq!(created.len(), 1, "{created:?}");
            assert_eq!(created[0].1, via);
            let completed: Vec<_> = completed
                .iter()
                .filter(|(detail, _)| detail.artifact_id == artifact.artifact_id)
                .collect();
            assert_eq!(completed.len(), 1, "{completed:?}");
            assert_eq!(completed[0].1, via);
        }
    })
    .await;
}

#[tokio::test]
async fn a_failed_upload_is_aborted_and_releases_its_bytes() {
    with_service(|harness| async move {
        let mesh = Mesh::start(&harness, &full_access()).await;
        let artifacts = mesh.for_request();

        // The body ends 20 MiB before its declared size, after two parts were sent.
        let short = artifacts
            .upload(name("short.bin"), octets(), streamed(20 * MIB + 1))
            .size(ObjectSize::new(40 * MIB).unwrap())
            .idempotency_key(IdempotencyKey::parse("failed-upload-retry").unwrap())
            .await;
        assert!(
            matches!(
                short,
                Err(ArtifactClientError::SizeMismatch {
                    declared,
                    read,
                }) if declared == 40 * MIB && read == 20 * MIB + 1
            ),
            "{short:?}"
        );
        // The same durable attempt must not turn its aborted artifact into success.
        let retry = artifacts
            .upload(name("short.bin"), octets(), streamed(20 * MIB + 1))
            .size(ObjectSize::new(40 * MIB).unwrap())
            .idempotency_key(IdempotencyKey::parse("failed-upload-retry").unwrap())
            .until_verified(Duration::from_secs(60))
            .await;
        assert!(
            matches!(retry, Err(ArtifactClientError::VerificationFailed { .. })),
            "an aborted idempotent upload must remain failed: {retry:?}"
        );
        // A body that fits one PUT but exceeds its declared size never reaches Artifact.
        let long = artifacts
            .upload(
                name("long.txt"),
                octets(),
                UploadBody::bytes("eleven bytes"),
            )
            .size(ObjectSize::new(10).unwrap())
            .await;
        assert!(
            matches!(long, Err(ArtifactClientError::TooLarge { limit: 10 })),
            "{long:?}"
        );

        let caller = user_caller();
        let store = harness.service.store();
        let open = store
            .uploads_page(
                &caller,
                Some(UploadState::Open),
                None,
                veoveo_types::PageSize::<100>::new(10).unwrap(),
            )
            .await
            .unwrap();
        assert!(open.items().is_empty(), "{:?}", open.items());
        let aborted = store
            .uploads_page(
                &caller,
                Some(UploadState::Aborted),
                None,
                veoveo_types::PageSize::<100>::new(10).unwrap(),
            )
            .await
            .unwrap();
        assert_eq!(aborted.items().len(), 1, "{:?}", aborted.items());
        let usage = store.storage_usage(&caller).await.unwrap();
        assert_eq!(usage.reserved_bytes, 0);
        assert_eq!(usage.stored_bytes, 0);
    })
    .await;
}
